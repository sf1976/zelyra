#!/bin/sh
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
OUTPUT="$ROOT/web/assets/zelyra-ui.v1.css"
TMP="$OUTPUT.tmp"
trap 'rm -f "$TMP"' EXIT HUP INT TERM
{
  printf '%s\n' '/* Zelyra UI CSS bundle v1.2.2; generated by scripts/build-zelyra-ui-assets.sh */'
  first=1
  for layer in reset base layout components utilities theme overrides; do
    if [ "$first" -eq 0 ]; then
      printf '\n'
    fi
    cat "$ROOT/web/assets/ui/$layer.css"
    first=0
  done
} > "$TMP"
if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$TMP" "$OUTPUT"; then
    echo "Zelyra UI CSS bundle is stale; run scripts/build-zelyra-ui-assets.sh" >&2
    exit 1
  fi
  exit 0
fi
mv "$TMP" "$OUTPUT"
trap - EXIT HUP INT TERM
