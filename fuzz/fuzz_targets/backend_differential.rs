#![no_main]

use libfuzzer_sys::fuzz_target;
use zelyra_mir::bytecode;
use zelyra_mir::execution::ExecutionLimits;
use zelyra_runtime::{check, execute_function, Value};

const LIMITS: ExecutionLimits = ExecutionLimits {
    max_steps: 10_000,
    max_stack_depth: 64,
};

fn generated_program(input: &[u8]) -> String {
    let bytes = if input.is_empty() { &[0][..] } else { input };
    let initial_count = usize::from(bytes[0] % 8) + 1;
    let mut values = (0..initial_count)
        .map(|index| i64::from(bytes.get(index + 1).copied().unwrap_or(0) % 101) - 50)
        .collect::<Vec<_>>();
    let initial = values
        .iter()
        .map(i64::to_string)
        .collect::<Vec<_>>()
        .join(", ");
    let mut statements = String::new();
    for (index, operation) in bytes.iter().skip(initial_count + 1).take(48).enumerate() {
        let raw = i64::from(*operation % 101) - 50;
        match operation % 4 {
            0 => {
                statements.push_str(&format!("push_mut(values, {raw})\n"));
                values.push(raw);
            }
            1 => {
                let target = usize::from(*operation) % values.len();
                statements.push_str(&format!("values[{target}] = {raw}\n"));
                values[target] = raw;
            }
            2 => {
                let target = usize::from(*operation) % values.len();
                statements.push_str(&format!("values[{target}] += {raw}\n"));
                values[target] += raw;
            }
            _ if values.len() > 1 => {
                statements.push_str(&format!("discard_{index} = pop_mut(values)\n"));
                values.pop();
            }
            _ => {
                statements.push_str(&format!("push_mut(values, {raw})\n"));
                values.push(raw);
            }
        }
    }
    format!(
        "fn main() -> Int {{\n mutable values: Int[] = [{initial}]\n {statements}\n mutable total = 0\n for value in values {{ total += value }}\n return total\n}}"
    )
}

fuzz_target!(|input: &[u8]| {
    if input.len() > 128 {
        return;
    }
    let source = generated_program(input);
    let Ok(tokens) = zelyra_lexer::lex(&source) else {
        return;
    };
    let Ok(program) = zelyra_parser::parse(&tokens) else {
        return;
    };
    if check(&program).is_err() {
        return;
    }
    let Ok(mir) = zelyra_mir::lower(&program) else {
        return;
    };
    let Ok(bytecode) = bytecode::compile(&mir, "main") else {
        return;
    };

    let expected = execute_function(&program, "main", Vec::new(), None)
        .expect("generated AST program should execute");
    let mir_value = zelyra_mir::execution::execute_function(&mir, "main", Vec::new(), LIMITS)
        .expect("generated MIR program should execute")
        .value;
    let encoded = bytecode::encode(&bytecode).expect("generated bytecode should encode");
    let decoded = bytecode::decode(&encoded).expect("generated bytecode should decode");
    let bytecode_value = bytecode::execute(&decoded, Vec::new(), LIMITS)
        .expect("generated bytecode program should execute")
        .value;

    assert!(matches!(expected, Value::Int(_)));
    assert_eq!(
        expected, mir_value,
        "AST/MIR generated-program mismatch\n{source}"
    );
    assert_eq!(
        expected, bytecode_value,
        "AST/Bytecode generated-program mismatch\n{source}"
    );
});
